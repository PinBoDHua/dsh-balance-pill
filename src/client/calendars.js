/** 日历覆盖的最后一年；用于「日历需要更新」提示。 */
export const CALENDAR_LAST_YEAR = Math.max(...CALENDAR_YEARS)

/** 日历覆盖的第一年。 */
export const CALENDAR_FIRST_YEAR = Math.min(...CALENDAR_YEARS)

/**
 * 某个年份是否在日历覆盖范围内。
 * @param year - 四位年份。
 * @returns 是否覆盖。
 */
export function calendarCovers(year) {
  return Number.isInteger(year) && year >= CALENDAR_FIRST_YEAR && year <= CALENDAR_LAST_YEAR
}
